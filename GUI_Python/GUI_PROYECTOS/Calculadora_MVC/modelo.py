class ModeloCalculadora:

    # Funcion para sumar dos numeros
    def sumar(self, numero1, numero2):

        # Realizamos la suma
        resultado = numero1 + numero2

        # Retornamos el resultado
        return resultado

    # Funcion para restar dos numeros
    def restar(self, numero1, numero2):

        # Realizamos la resta
        resultado = numero1 - numero2

        # Retornamos el resultado
        return resultado
