# Programa: IEMB | Todos los Tipos de Variables COMPLETO
print("Bienvenido a IEMB | Tipos de Variables")
# Tipo texto (str)
nombre = input("Escribe tu nombre: ")
# Tipo entero (int)
edad = int(input("Escribe tu edad: "))
# Tipo decimal (float)
estatura = float(input("Escribe tu estatura (ej: 1.70): "))
# Tipo booleano (bool)
es_estudiante = True
# Lista (list)
materias = ["Tecnologia", "Matematicas", "Ciencias"]
# Tupla (tuple)
coordenadas = (10, 20)
# Diccionario (dict)
persona = {"nombre": nombre, "edad": edad}
# Conjunto (set)
numeros_unicos = {1, 2, 3, 3, 2}
# Numero complejo (complex)
numero_complejo = 2 + 3j
# Tipo None (NoneType)
dato_vacio = None
# Mostrar resultados
print("Nombre:", nombre)
print("Edad:", edad)
print("Estatura:", estatura)
print("Es estudiante:", es_estudiante)
print("Materias:", materias)
print("Coordenadas:", coordenadas)
print("Datos persona:", persona)
print("Numeros unicos:", numeros_unicos)
print("Numero complejo:", numero_complejo)
print("Dato vacio:", dato_vacio)
print("Gracias por usar el programa")